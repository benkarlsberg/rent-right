import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { DISCLAIMER_EN } from "@/lib/disclaimer";
import { deleteAccountDocument, HOME_DESCRIPTION, homeIntro, iconLinks, injectHomeHtml, privacyDocument, supportDocument, termsDocument } from "@/lib/legal-html";
import { SHARE_DESCRIPTION, SHARE_IMAGE, SHARE_IMAGE_ALT, SHARE_TITLE, SHARE_URL, shareMeta } from "@/lib/share-meta";
import { GET as deleteAccount } from "@/app/delete-account/route";
import { GET as support } from "@/app/support/route";
import { GET as privacy } from "@/app/privacy/route";
import { GET as terms } from "@/app/terms/route";

describe("public legal pages", () => {
  it("puts the contact address and the disclaimer in crawlable HTML", async () => {
    expect(privacyDocument).toContain("support@rentrightportal.com");
    expect(privacyDocument).not.toContain("gmail.com");
    expect(privacyDocument).toContain("not a law firm");
    expect(privacyDocument).toContain("only after you confirm");
    expect(privacyDocument).toContain("chat messages");
    expect(privacyDocument).toContain("encrypted before they are stored");
    expect(termsDocument).toContain(DISCLAIMER_EN);
    expect(termsDocument).toContain("not a decision about your home");
    expect(homeIntro).toContain("<h1");
    expect(homeIntro).toContain("Rent Right");
    expect(homeIntro).toContain(HOME_DESCRIPTION);
    expect(homeIntro).toContain('href="/"');
    expect(homeIntro).toContain('href="/privacy"');
    expect(homeIntro).toContain('href="/terms"');
    const shell = `<html><head><title>Old</title></head><body><div id="root"></div><nav id="rr-legal"><a href="/privacy">Privacy</a></nav></body></html>`;
    const injected = injectHomeHtml(shell);
    expect(injected).toContain("<title>Rent Right</title>");
    expect(injected).toContain('name="description"');
    expect(injected).toContain(HOME_DESCRIPTION);
    expect(injected).toContain('property="og:site_name" content="Rent Right"');
    expect(injected).toContain(shareMeta);
    expect(injected).toContain(`property="og:title" content="${SHARE_TITLE}"`);
    expect(injected).toContain('property="og:type" content="website"');
    expect(injected).toContain(`property="og:url" content="${SHARE_URL}"`);
    expect(injected).toContain(`property="og:image" content="${SHARE_IMAGE}"`);
    expect(injected).toContain('property="og:image:width" content="1200"');
    expect(injected).toContain('property="og:image:height" content="630"');
    expect(injected).toContain(`property="og:image:alt" content="${SHARE_IMAGE_ALT}"`);
    expect(injected).toContain('name="twitter:card" content="summary_large_image"');
    expect(injected).toContain(`name="twitter:title" content="${SHARE_TITLE}"`);
    expect(injected).toContain(`name="twitter:image" content="${SHARE_IMAGE}"`);
    expect(injected).toContain(`rel="canonical" href="${SHARE_URL}"`);
    expect(injected).toContain('<div id="root"><main id="rr-home"');
    expect(injected).not.toContain('id="rr-legal"');
    expect(injected).toContain(iconLinks);
    expect(iconLinks).toContain('href="/favicon.svg?v=2"');
    expect(iconLinks).toContain('href="/apple-touch-icon.png?v=3"');
    const again = injectHomeHtml(injected);
    expect(again.match(/href="\/favicon\.svg\?v=2"/g)).toHaveLength(1);
    expect(again.match(/property="og:title"/g)).toHaveLength(1);
    expect(again.match(/property="og:image"/g)).toHaveLength(1);
    expect(again.match(/rel="canonical"/g)).toHaveLength(1);
    const replaced = injectHomeHtml(`<html><head><link rel="icon" href="/favicon.ico"></head><body><div id="root"></div></body></html>`);
    expect(replaced.match(/rel="icon"/g)).toHaveLength(4);
    expect(privacyDocument).toContain('href="/favicon.svg?v=2"');
    expect(termsDocument).toContain('href="/apple-touch-icon.png?v=3"');
    expect(termsDocument).toContain('href="/manifest.webmanifest?v=3"');
    const privacyBody = await (await privacy()).text();
    const termsBody = await (await terms()).text();
    expect(privacyBody).toContain("<h1>Privacy policy</h1>");
    expect(privacyBody).toContain("<title>Privacy policy · Rent Right</title>");
    expect(privacyBody).toContain('name="description" content="What Rent Right stores for California renters, and what it sends."');
    expect(termsBody).toContain("<h1>Terms of use</h1>");
    expect(termsBody).toContain("<title>Terms of use · Rent Right</title>");
    expect(termsBody).toContain('name="description" content="How Rent Right keeps records and drafts landlord messages for California renters."');
    expect(privacyBody).not.toContain("id=\"root\"");
    expect(deleteAccountDocument).toContain("Export your evidence packet first");
    expect(deleteAccountDocument).toContain("landlord communications");
    expect(deleteAccountDocument).toContain(DISCLAIMER_EN);
    expect(deleteAccountDocument).toContain("Ajustes");
    expect(privacyDocument).toContain('href="/delete-account"');
    expect(supportDocument).toContain("support@rentrightportal.com");
    expect(supportDocument).not.toContain("gmail.com");
    expect(supportDocument).toContain("https://app.rentrightportal.com/privacy");
    expect(supportDocument).toContain('href="/terms"');
    expect(supportDocument).toContain("<h1>Support</h1>");
    expect(homeIntro).toContain('href="/support"');
    const supportBody = await (await support()).text();
    expect(supportBody).toContain("<h1>Support</h1>");
    expect(supportBody).toContain("support@rentrightportal.com");
    expect(supportBody).not.toContain("gmail.com");
    expect(supportBody).not.toContain("id=\"root\"");
    const deleteBody = await (await deleteAccount()).text();
    expect(deleteBody).toContain("<h1>Delete your account</h1>");
    expect(deleteBody).not.toContain("id=\"root\"");
    const root = join(dirname(fileURLToPath(import.meta.url)), "..");
    const preview = readFileSync(join(root, "public/og.png"));
    expect(preview.subarray(0, 8).toString("hex")).toBe("89504e470d0a1a0a");
    expect(preview.readUInt32BE(16)).toBe(1200);
    expect(preview.readUInt32BE(20)).toBe(630);
    expect(preview.length).toBeLessThan(5 * 1024 * 1024);
    expect(readFileSync(join(root, "mobile/public/og.png")).equals(preview)).toBe(true);
    const webHead = readFileSync(join(root, "mobile/src/app/+html.tsx"), "utf8");
    expect(webHead).toContain(SHARE_TITLE);
    expect(webHead).toContain(SHARE_DESCRIPTION);
    expect(webHead).toContain(SHARE_IMAGE);
    expect(webHead).toContain(SHARE_IMAGE_ALT);
    expect(webHead).toContain('content="summary_large_image"');
    expect(webHead).toContain(`href="${SHARE_URL}"`);
    const workerHead = readFileSync(join(root, "app/layout.tsx"), "utf8");
    expect(workerHead).toContain("SHARE_TITLE");
    expect(workerHead).toContain("SHARE_IMAGE");
    expect(workerHead).toContain('card: "summary_large_image"');
    expect(workerHead).toContain("canonical: SHARE_URL");
  });
});
